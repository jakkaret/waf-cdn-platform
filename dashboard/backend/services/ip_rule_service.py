import time
import re
import ipaddress
import logging
from pathlib import Path
from typing import List, Dict, Optional
from services.rule_manager import RuleManager, NginxConfigError

logger = logging.getLogger(__name__)

CUSTOM_RULES_DIR = Path(__file__).resolve().parent.parent.parent.parent / "modsecurity" / "custom-rules"
CUSTOM_RULES_DIR.mkdir(parents=True, exist_ok=True)

BLOCKLIST_TXT = CUSTOM_RULES_DIR / "global_blocklist.txt"
WHITELIST_TXT = CUSTOM_RULES_DIR / "global_whitelist.txt"
BLOCKLIST_CONF = CUSTOM_RULES_DIR / "custom-000000-global-blocklist.conf"
WHITELIST_CONF = CUSTOM_RULES_DIR / "custom-000001-global-whitelist.conf"


class IPRuleService:
    """Global IP/CIDR block and allow rules (waf.ip_rules), rendered into the
    ModSecurity block/allow files. No I/O at construction (api/ip_rules.py
    builds this at import time); the files are rendered on first use and by
    the hourly retention worker."""

    def __init__(self):
        from services.pg_store import PgIPRuleRepository
        self.rule_manager = RuleManager()
        self._pg = PgIPRuleRepository()
        self._synced = False

    def _ensure_synced(self):
        if not self._synced:
            self._sync_files_from_db()

    def _validate_ip_or_cidr(self, ip_str: str) -> str:
        ip_str = ip_str.strip()
        try:
            if "/" in ip_str:
                network = ipaddress.ip_network(ip_str, strict=False)
                return str(network)
            else:
                ip_obj = ipaddress.ip_address(ip_str)
                return str(ip_obj)
        except ValueError:
            raise ValueError(f"Invalid IP address or CIDR notation: '{ip_str}'")

    def _reload_nginx(self) -> bool:
        """Reload nginx; returns whether the change is live. An invalid config is
        logged as an error instead of being silently skipped (F-037)."""
        from services.rule_manager import RULES_LOCK
        try:
            with RULES_LOCK:  # P4.3: one lock for every rule writer
                self.rule_manager.reload_nginx()
            return True
        except NginxConfigError as e:
            logger.error(f"IP rules saved but NOT applied: nginx -t failed: {e}")
        except Exception as e:
            logger.warning(f"Nginx reload notification skipped: {e}")
        return False

    def _sync_files_from_db(self):
        """Re-generate global_blocklist.txt, global_whitelist.txt and the corresponding ModSec .conf files."""
        # Expiry stays here (not in run_retention()): an expired ban has to
        # leave the rendered ModSecurity files too.
        from services.rule_manager import RULES_LOCK
        self._pg.delete_expired()
        with RULES_LOCK:  # P4.3: one lock for every rule writer
            changed = self._write_files(self._pg.ips("block"), self._pg.ips("allow"))
        self._synced = True
        return changed

    @staticmethod
    def _files_snapshot() -> tuple:
        return tuple(p.read_text(encoding="utf-8") if p.exists() else None
                     for p in (BLOCKLIST_TXT, WHITELIST_TXT, BLOCKLIST_CONF, WHITELIST_CONF))

    def _write_files(self, blocked_ips: List[str], allowed_ips: List[str]) -> bool:
        """Render the four files from the given lists; True when any changed."""
        before = self._files_snapshot()
        # 1. Write Blocklist Text
        BLOCKLIST_TXT.write_text("\n".join(blocked_ips) + ("\n" if blocked_ips else ""), encoding="utf-8")
        if blocked_ips:
            BLOCKLIST_CONF.write_text(
                "# Global Blocklist Rule (Auto-generated by CloudWAF)\n"
                "SecRule REMOTE_ADDR \"@ipMatchFromFile /opt/custom-rules/global_blocklist.txt\" \\\n"
                "    \"id:1000000,phase:1,deny,status:403,log,msg:'Global IP Blocklist: Connection Dropped'\"\n",
                encoding="utf-8"
            )
        else:
            # Remove or clear conf file if no blocked IPs to avoid error
            if BLOCKLIST_CONF.exists():
                BLOCKLIST_CONF.unlink()

        # 2. Write Whitelist Text
        WHITELIST_TXT.write_text("\n".join(allowed_ips) + ("\n" if allowed_ips else ""), encoding="utf-8")
        if allowed_ips:
            WHITELIST_CONF.write_text(
                "# Global Whitelist Rule (Auto-generated by CloudWAF)\n"
                "SecRule REMOTE_ADDR \"@ipMatchFromFile /opt/custom-rules/global_whitelist.txt\" \\\n"
                # id 9100000: 1000001 is already used by custom-100001.conf, and a
                # duplicate id makes `nginx -t` fail on Main and every edge (F-033).
                "    \"id:9100000,phase:1,allow,nolog,msg:'Global IP Whitelist: Bypass WAF'\"\n",
                encoding="utf-8"
            )
        else:
            if WHITELIST_CONF.exists():
                WHITELIST_CONF.unlink()
        return self._files_snapshot() != before

    def list_rules(self, rule_type: Optional[str] = None, search: Optional[str] = None) -> List[Dict]:
        self._sync_files_from_db()
        now = int(time.time())
        rules = self._pg.list(rule_type, search)
        for item in rules:
            item["remaining_seconds"] = max(0, item["expires_at"] - now) if item["expires_at"] else None
        return rules

    def add_rule(self, ip: str, rule_type: str = "block", reason: str = "Manual entry",
                 added_by: str = "admin", duration_seconds: Optional[int] = None, source: str = "manual") -> Dict:
        validated_ip = self._validate_ip_or_cidr(ip)
        rule_type = rule_type.lower()
        if rule_type not in ["block", "allow"]:
            raise ValueError("rule_type must be 'block' or 'allow'")

        now = int(time.time())
        expires_at = (now + duration_seconds) if (duration_seconds and duration_seconds > 0) else None

        self._pg.upsert(validated_ip, rule_type, reason.strip()[:200], added_by[:64], expires_at, source[:32])
        self._sync_files_from_db()
        applied = self._reload_nginx()
        return {"status": "success", "ip": validated_ip, "rule_type": rule_type,
                "expires_at": expires_at, "nginx_applied": applied}

    def _valid_ips(self, ips: List[str]) -> List[str]:
        """Only well-formed addresses reach PostgreSQL's inet column (a bad
        one would abort the statement with a 500 instead of "not found")."""
        valid = []
        for ip in ips:
            try:
                valid.append(self._validate_ip_or_cidr(ip))
            except ValueError:
                continue
        return valid

    def delete_rule(self, ip: str) -> bool:
        valid = self._valid_ips([ip.strip()])
        deleted = bool(valid) and self._pg.delete(valid) > 0
        if deleted:
            self._sync_files_from_db()
            self._reload_nginx()
        return deleted

    def bulk_delete(self, ips: List[str]) -> int:
        if not ips:
            return 0
        deleted_count = self._pg.delete(self._valid_ips(ips))
        if deleted_count > 0:
            self._sync_files_from_db()
            self._reload_nginx()
        return deleted_count

    def get_stats(self) -> Dict:
        self._ensure_synced()
        return self._pg.stats()
