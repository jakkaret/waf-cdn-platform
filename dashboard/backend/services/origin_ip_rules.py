"""Per-site IP access list: the IPs or CIDR ranges one site blocks or lets
through (waf.origin_ip_rules, migration 0015).

Owners and editors manage them on the site's page; viewers read them; nobody
else sees them. Each site with rules gets one file in the WAF rules directory,

    siteip-<origin_id>.conf

holding a block chain and an allow chain. The first link of each chain only
fires for requests the host map (managed-00-hostmap.conf) attributed to this
site, so a rule never touches another site's traffic. The files load after
the platform-wide lists (custom-000000/000001), so the platform blocklist and
allowlist always win over a site's own list; within a site, block wins over
allow. "allow" skips the WAF for that IP on that site only.

Rule ids: 3500000 + 2 * slot (block) and + 1 (allow), one slot per site from
waf.origin_rule_slots, never reused. Expired rows are removed by the
retention worker, which re-renders the affected sites.
"""
from __future__ import annotations

import ipaddress
import logging
import os
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from db import pool
from services.rule_manager import RULES_LOCK as _lock

logger = logging.getLogger(__name__)

ID_BASE = 3_500_000
ACTIONS = ("block", "allow")
MAX_RULES_PER_SITE = int(os.getenv("SITE_IP_RULES_PER_ORIGIN", "500"))
MAX_NOTE_LENGTH = 200
MAX_HOURS = 24 * 365
# Narrowest a site may list as one entry: a site blocking a whole /8 or /16 is
# almost always a typo, and the platform list exists for that.
MIN_PREFIX = {4: 16, 6: 32}

_ORIGIN_ID_OK = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_FILE = re.compile(r"^siteip-([A-Za-z0-9_-]{1,64})\.conf$")


class SiteIpRuleError(ValueError):
    pass


def normalize_ip(value: Any) -> str:
    """'203.0.113.7' or '198.51.100.0/24' (host bits cleared); raises on
    anything else or a range broader than MIN_PREFIX."""
    try:
        net = ipaddress.ip_network(str(value or "").strip(), strict=False)
    except ValueError:
        raise SiteIpRuleError("not an IP address or CIDR range")
    if net.prefixlen < MIN_PREFIX[net.version]:
        raise SiteIpRuleError(f"range too broad: IPv{net.version} /{MIN_PREFIX[net.version]} or narrower")
    return str(net.network_address) if net.num_addresses == 1 else str(net)


def _shown_ip(value: Any) -> str:
    net = ipaddress.ip_network(str(value), strict=False)
    return str(net.network_address) if net.num_addresses == 1 else str(net)


def _row(r: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "id": r["id"], "ip": _shown_ip(r["ip"]), "action": r["action"], "note": r["note"],
        "expires_at": r["expires_at"].isoformat() if r["expires_at"] else None,
        "created_by": r["created_by"], "created_at": r["created_at"].isoformat(),
    }


def list_rules(origin_id: str) -> List[Dict[str, Any]]:
    return [_row(r) for r in pool.q(
        "SELECT * FROM origin_ip_rules WHERE origin_id = %s::uuid AND (expires_at IS NULL OR expires_at > now()) "
        "ORDER BY action, created_at DESC", (origin_id,))]


def _active(origin_id: str, action: str) -> List[str]:
    return [_shown_ip(r["ip"]) for r in pool.q(
        "SELECT ip FROM origin_ip_rules WHERE origin_id = %s::uuid AND action = %s "
        "AND (expires_at IS NULL OR expires_at > now()) ORDER BY ip", (origin_id, action))]


def _slot(origin_id: str) -> int:
    pool.exec_("INSERT INTO origin_rule_slots (origin_id) VALUES (%s) ON CONFLICT DO NOTHING", (origin_id,))
    return int(pool.q1("SELECT slot FROM origin_rule_slots WHERE origin_id = %s::uuid", (origin_id,))["slot"])


def render(origin_id: str, slot: int, blocked: List[str], allowed: List[str]) -> Optional[str]:
    """The .conf text for one site, or None when it lists nothing."""
    if not _ORIGIN_ID_OK.match(origin_id):
        raise SiteIpRuleError("bad origin id")
    if not blocked and not allowed:
        return None
    base = ID_BASE + 2 * slot
    tags = f"tag:'site-ip-rule',tag:'origin:{origin_id}'"
    lines = [f"# Site IP access list for {origin_id} -- generated by services/origin_ip_rules.py, do not edit"]
    for ids, action, entries, msg in (
        (base, "deny,status:403,log", blocked, "Site IP blocklist"),
        (base + 1, "allow,nolog", allowed, "Site IP allowlist: bypass WAF"),
    ):
        if not entries:
            continue
        lines.append(f'SecRule TX:waf_origin_id "@streq {origin_id}" '
                     f'"id:{ids},phase:1,{action},msg:\'{msg}\',{tags},chain"')
        lines.append(f'    SecRule REMOTE_ADDR "@ipMatch {",".join(entries)}" "t:none"')
    return "\n".join(lines) + "\n"


class SiteIpRuleService:
    """Rows in PostgreSQL, one rendered file per site. Uses the RuleManager's
    directory and its nginx test/reload, like services/tenant_rules.py."""

    def __init__(self, rule_manager):
        self.rm = rule_manager

    @property
    def dir(self) -> Path:
        return Path(self.rm.rules_dir)

    def _path(self, origin_id: str) -> Path:
        return self.dir / f"siteip-{origin_id}.conf"

    def sync(self, origin_id: str) -> bool:
        """Write this site's file from the database (or remove it), nginx -t,
        reload. Restores the previous file if the test fails. Returns whether
        anything changed. Call with RULES_LOCK held."""
        path = self._path(origin_id)
        blocked, allowed = _active(origin_id, "block"), _active(origin_id, "allow")
        # No slot for a site that lists nothing (it may no longer exist).
        text = render(origin_id, _slot(origin_id), blocked, allowed) if blocked or allowed else None
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            return False
        if text is None:
            path.unlink(missing_ok=True)
        else:
            path.write_text(text, encoding="utf-8")
        try:
            self.rm.test_nginx()
            self.rm.reload_nginx()
        except Exception:
            if old is None:
                path.unlink(missing_ok=True)
            else:
                path.write_text(old, encoding="utf-8")
            raise
        return True

    def add(self, origin_id: str, ip: Any, action: str, note: str = "", hours: Optional[int] = None,
            user: Optional[dict] = None) -> Dict[str, Any]:
        ip = normalize_ip(ip)
        action = str(action or "").strip().lower()
        if action not in ACTIONS:
            raise SiteIpRuleError("action must be block or allow")
        note = str(note or "").strip()
        if len(note) > MAX_NOTE_LENGTH or "\n" in note or "\r" in note:
            raise SiteIpRuleError(f"note: one line, at most {MAX_NOTE_LENGTH} characters")
        expires_at = None
        if hours is not None:
            if not 1 <= int(hours) <= MAX_HOURS:
                raise SiteIpRuleError(f"hours must be 1-{MAX_HOURS}")
            expires_at = datetime.now(timezone.utc) + timedelta(hours=int(hours))
        by = (user or {}).get("username") or (user or {}).get("user_id") or ""
        with _lock:
            if len(list_rules(origin_id)) >= MAX_RULES_PER_SITE:
                raise SiteIpRuleError(f"a site can list at most {MAX_RULES_PER_SITE} IPs")
            # An expired leftover of the same IP is replaced, not reported as a duplicate.
            pool.exec_("DELETE FROM origin_ip_rules WHERE origin_id = %s::uuid AND ip = %s::cidr "
                       "AND expires_at IS NOT NULL AND expires_at <= now()", (origin_id, ip))
            row = pool.q1("INSERT INTO origin_ip_rules (origin_id, ip, action, note, expires_at, created_by) "
                          "VALUES (%s, %s, %s, %s, %s, %s) ON CONFLICT (origin_id, ip) DO NOTHING RETURNING *",
                          (origin_id, ip, action, note, expires_at, by))
            if not row:
                raise SiteIpRuleError(f"{ip} is already on this site's list")
            try:
                self.sync(origin_id)
            except Exception:
                pool.exec_("DELETE FROM origin_ip_rules WHERE id = %s", (row["id"],))
                raise
        return _row(row)

    def delete(self, origin_id: str, rule_id: int) -> Dict[str, Any]:
        with _lock:
            row = pool.q1("DELETE FROM origin_ip_rules WHERE id = %s AND origin_id = %s::uuid RETURNING *",
                          (int(rule_id), origin_id))
            if not row:
                raise KeyError(rule_id)
            try:
                self.sync(origin_id)
            except Exception:
                pool.exec_("INSERT INTO origin_ip_rules (id, origin_id, ip, action, note, expires_at, created_by, "
                           "created_at) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)",
                           (row["id"], row["origin_id"], row["ip"], row["action"], row["note"],
                            row["expires_at"], row["created_by"], row["created_at"]))
                raise
        return _row(row)

    def expire(self) -> int:
        """Drop expired rows and re-render the sites they belonged to, plus
        any site whose file no longer matches the database (a file left for a
        deleted site, a missed reload). Returns the rows removed."""
        with _lock:
            gone = pool.q("DELETE FROM origin_ip_rules WHERE expires_at IS NOT NULL AND expires_at <= now() "
                          "RETURNING origin_id::text AS origin_id")
            sites = {r["origin_id"] for r in gone}
            sites |= {r["origin_id"] for r in pool.q("SELECT DISTINCT origin_id::text AS origin_id FROM origin_ip_rules")}
            sites |= {m.group(1) for p in self.dir.glob("siteip-*.conf") if (m := _FILE.match(p.name))}
            for origin_id in sorted(sites):
                try:
                    self.sync(origin_id)
                except Exception as exc:
                    logger.warning("site IP rules for %s not re-rendered: %s", origin_id, exc)
        return len(gone)
